import { execFileSync } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

// 从 FastAPI 的路由/Pydantic 模型导出，无需启动服务或访问数据库。
const root = fileURLToPath(new URL("../../", import.meta.url));
const schema = execFileSync(process.env.PYTHON ?? `${root}.venv/bin/python`, [
  "-c", "import json; from app.main import app; print(json.dumps(app.openapi()))",
], { cwd: root, env: { ...process.env, DEBUG: "1" }, encoding: "utf8", maxBuffer: 8 * 1024 * 1024 });
const output = new URL("../src/generated/api.d.ts", import.meta.url);
const source = "// Generated by npm run api:generate. Do not edit.\n" + astToString(await openapiTS(JSON.parse(schema)));
if (process.argv.includes("--check")) {
  if (await readFile(output, "utf8") !== source) {
    throw new Error("API types are stale. Run npm run api:generate and include the result.");
  }
  console.log("API types match FastAPI.");
} else {
  const { mkdir } = await import("node:fs/promises");
  await mkdir(new URL("../src/generated/", import.meta.url), { recursive: true });
  await writeFile(output, source);
  console.log("Generated src/generated/api.d.ts from FastAPI.");
}
