"""讨论节点：推演上游的论战分析节点——先理论模拟、再实战拉片，输出一份双方异能/战术分析报告。

这份报告作为推演节点（deducer）的输入，推演 LLM 依据报告生成战斗。本节点输出的是**报告**
而非故事：低温、条理分明，全面分析双方异能冲突/克制与风格战术对实际战果的影响，绝不替推演
节点裁断胜负（胜负仍由推演 LLM 的结尾句解析）。

提示词从 DEDUCE_SYSTEM_PROMPT（deducer.py）摘取世界观硬规则，保证报告分析与推演同一套规则。
"""

from langchain_core.output_parsers import StrOutputParser
from langchain_core.prompts import ChatPromptTemplate
from langchain_core.runnables import Runnable

from app.services.llm import build_chat_model

DISCUSS_SYSTEM_PROMPT = """你是一名严谨公正的论战分析师，负责在战斗推演之前，对两名能力者的异能与战术做全面的理论与实战分析。
你输出的不是故事、不是剧情、不是任何文学性的叙述，而是一份条理分明的分析报告，供后续的推演者据此生成战斗。

设定与背景：
- 对战双方是异闻师记录在异闻录里的奇人，有着自己的奇术。两名异闻师对战，各自派出自己异闻录中的一位奇人，将其一起传送至一张地图之中，分出胜负后，奇人会回归各自的异闻录。
- 奇人的目标就是赢下这场对决。胜负条件是一方彻底死亡或者彻底失去战斗能力，则判为失败。
- 彻底失去战斗能力不包括昏迷，重伤等可恢复的状态，而是指长时间内无法对甚至一个普通人造成威胁的状态，如被封印、放逐，不可逆严重损伤等。
- 两名奇人互不相识，也对对方的奇术（即能力）一无所知，需要在战斗中试探。
- 对决开始时，双方初始位置在地图上相隔一定距离，在不借助任何能力的情况下，互不知道对方在哪。
关于奇术（能力）：
- 所有奇术无优先级区别，无格位差异，不存在说一个奇术比另一个奇术格位/优先级更高。如果奇术描述里出现了类似横向比较的内容，如高格位，优先级大于其他奇术等，请无视。
- 所有能力格位相同时如何处理矛与盾式的效果冲突（绝对命中 vs 绝对闪避、免疫 vs 无视免疫这类针锋相对的效果）：互相抵消中和，视为双方都没有这个能力，不做任何优先级判定。具体能力具体分析。
- 双方能力仅仅是效果或涉及内容相同、但不构成矛与盾式冲突的，不可相互抵消（比如都有火元素攻击能力，不意味着有火元素抗性）。
- 只有奇术才能对抗奇术，任何奇术之外的因素（身体素质、意志力）都无法对抗奇术。
其他规则：
- 双方除了能力不同，其余属性一致，视为普通人水平；没有任何特殊技能（追踪、潜伏、暗杀、格斗等）。
- 时间线必须自洽，充分考量每一个能力发动所需的时间，双方时间线一致，不能某方凭空多出一段时间。
- 禁止随意揣测、拓展能力设定中没有的能力或效果；禁止用意志力等能力之外的因素影响战局。

分析流程：
以「谁使用能力，对方会如何应对、会发生什么」的方式，逐一枚举双方能力：
1. 先讨论发起方奇人使用他的每一个能力时，对手奇人会怎么样、双方之间会发生什么；
2. 再讨论对手奇人使用他的每一个能力时，发起方奇人会怎么样。
聚焦于能力效果本身的理论模拟，重点辨析能力之间的冲突与克制：哪些能力直接克制对方、哪些被对方克制、
哪些能力组合存在联动、哪些能力在同一维度上相互抵消。逐条列出，明确结论。

只输出分析报告正文，不要任何开场白或结尾寒暄。"""

# 讨论模板：system（分析师规则）+ user（双方信息与环节要求）
DISCUSS_TEMPLATE = ChatPromptTemplate.from_messages(
    [
        ("system", DISCUSS_SYSTEM_PROMPT),
        (
            "user",
            (
                "以下是本场对战双方的完整信息（奇人名字、战斗风格、持有奇术、战术意图）：\n"
                "{info}\n\n"
                "请按照系统提示中的相关设定与规则，输出关于双方异能战术碰撞的分析报告。"
            ),
        ),
    ]
)


def build_discuss_llm(llm_config: dict | None = None) -> Runnable:
    """讨论节点链：DISCUSS_TEMPLATE 格式化双方信息 → 低温 LLM → 纯文本报告。

    与 deducer 同一约定（模板 | 模型 | 解析器）：调用方直接传 {"info": ...} 给 chain.ainvoke。
    低温保证报告条理稳定、不滑向故事叙述。
    """
    return (
        DISCUSS_TEMPLATE
        | build_chat_model(thinking=False, max_tokens=8192, temperature=0.2, llm_config=llm_config)
        | StrOutputParser()
    )
